    private void refreshEdtTable() {
        try {
            EdtControllers controller = new EdtControllers();
            ArrayList<EdtModels> edts = controller.getAllEdts();

            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("ID EDT");
            model.addColumn("ID Salle");
            model.addColumn("ID Prof");
            model.addColumn("ID Classe");
            model.addColumn("Cours");
            model.addColumn("Date");

            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            for (EdtModels edt : edts) {
                model.addRow(new Object[]{
                    edt.getIdEDT(),
                    edt.getIDSalle(),
                    edt.getIdProf(),
                    edt.getIDClasse(),
                    edt.getCours(),
                    (edt.getDate() != null) ? dateFormat.format(edt.getDate()) : ""
                });
            }

            edtTable.setModel(model);
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Erreur lors du rafraîchissement de la table : " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Erreur lors du chargement des emplois : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }

