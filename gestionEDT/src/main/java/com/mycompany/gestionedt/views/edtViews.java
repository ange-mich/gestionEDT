    private void addEdtButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addEdtButtonActionPerformed
        // TODO add your handling code here:
    String idEDT = idedtTextField.getText().trim();
    String idSalleStr = idsalleTextField.getText().trim();
    String idProf = idprofTextField.getText().trim();
    String IDClasse = idclasseTextField.getText().trim();
    String Cours = coursTextField.getText().trim();
    Date selectedDate = (Date) dateSpinner.getValue();
    java.sql.Timestamp Date = new java.sql.Timestamp(selectedDate.getTime());

    if (!idEDT.isEmpty() && !idSalleStr.isEmpty() && !idProf.isEmpty() && !IDClasse.isEmpty() && !Cours.isEmpty()) {
        try {
            int IDSalle = Integer.parseInt(idSalleStr);

            EdtControllers controller = new EdtControllers();
            if (addEdtButton.getText().equals("Save")) {
                EdtModels edt = new EdtModels(idEDT, IDSalle, idProf, IDClasse, Cours, Date);
                controller.updateEdt(edt);
                JOptionPane.showMessageDialog(this, "Emploi mis à jour avec succès ! ID : " + idEDT);
                addEdtButton.setText("Ajouter");
                idedtTextField.setEditable(true);
            } else {
                EdtModels edt = controller.ajouterEdt(idEDT, IDSalle, idProf, IDClasse, Cours, Date);
                JOptionPane.showMessageDialog(this, "Emploi ajouté avec succès ! ID : " + edt.getIdEDT());
            }

            clearEdtFields();
            refreshEdtTable();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID Salle doit être un nombre valide !", "Erreur", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Erreur lors de l'ajout/mise à jour : " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Une erreur est survenue : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !", "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_addEdtButtonActionPerformed

    private void editEdtbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editEdtbuttonActionPerformed
        // TODO add your handling code here:
        int selectedRow = edtTable.getSelectedRow();
    if (selectedRow != -1) {
        DefaultTableModel model = (DefaultTableModel) edtTable.getModel();
        String idEDT = model.getValueAt(selectedRow, 0).toString();
        String IDSalleStr = model.getValueAt(selectedRow, 1).toString();
        String idProf = model.getValueAt(selectedRow, 2).toString();
        String IDClasse = model.getValueAt(selectedRow, 3).toString();
        String Cours = model.getValueAt(selectedRow, 4).toString();
        String dateStr = model.getValueAt(selectedRow, 5).toString();
        try {
            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            Date date = dateFormat.parse(dateStr);
            dateSpinner.setValue(date);
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Erreur lors du parsing de la date : " + e.getMessage());
        }

        idedtTextField.setText(idEDT);
        idsalleTextField.setEditable(false);
        idsalleTextField.setText(IDSalleStr);
        idprofTextField.setText(idProf);
        idclasseTextField.setText(IDClasse);
        coursTextField.setText(Cours);
        addEdtButton.setText("Save");
    } else {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner un emploi à modifier !", "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_editEdtbuttonActionPerformed

    private void deleteEdtButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteEdtButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = edtTable.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) edtTable.getModel();
            String idEDT = model.getValueAt(selectedRow, 0).toString();

            int confirm = JOptionPane.showConfirmDialog(this, "Êtes-vous sûr de vouloir supprimer l'emploi avec ID " + idEDT + " ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    EdtControllers controller = new EdtControllers();
                    controller.deleteEdt(idEDT);
                    refreshEdtTable();
                    JOptionPane.showMessageDialog(this, "Emploi supprimé avec succès !");
                } catch (Exception e) {
                    logger.log(Level.SEVERE, "Erreur lors de la suppression : " + e.getMessage());
                    JOptionPane.showMessageDialog(this, "Une erreur est survenue : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner un emploi à supprimer !", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_deleteEdtButtonActionPerformed
