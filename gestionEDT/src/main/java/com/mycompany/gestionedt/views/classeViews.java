    private void refreshClasseTable() {
        try {
            ClasseControllers controller = new ClasseControllers();
            ArrayList<ClasseModels> classes = controller.getAllClasses();

            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("ID Classe");
            model.addColumn("Niveau");

            for (ClasseModels classe : classes) {
                model.addRow(new Object[]{
                    classe.getIdclasse(),
                    classe.getNiveau()
                });
            }

            classeTable.setModel(model);
        } catch (Exception e) {
            logger.log(Level.SEVERE, "Erreur lors du rafraîchissement de la table : " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Erreur lors du chargement des classes : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }

