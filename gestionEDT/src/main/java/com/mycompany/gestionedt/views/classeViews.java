    private void addClasseButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addClasseButtonActionPerformed
        // TODO add your handling code here:
    String idClasseStr = idclasseTextField.getText().trim();
        String niveau = niveauComboBox.getSelectedItem() != null ? niveauComboBox.getSelectedItem().toString().trim() : "";

        if (!idClasseStr.isEmpty() && !niveau.isEmpty()) {
            try {
                int idClasse = Integer.parseInt(idClasseStr);

                ClasseControllers controller = new ClasseControllers();
                if (addClasseButton.getText().equals("Save")) {
                    ClasseModels classe = new ClasseModels(idClasse, niveau);
                    controller.updateClasse(classe);
                    JOptionPane.showMessageDialog(this, "Classe mise à jour avec succès ! ID : " + idClasse);
                    addClasseButton.setText("Ajouter");
                    idclasseTextField.setEditable(true);
                } else {
                    ClasseModels classe = controller.ajouterClasse(idClasse, niveau);
                    JOptionPane.showMessageDialog(this, "Classe ajoutée avec succès ! ID : " + classe.getIdclasse());
                }

                clearClasseFields();
                refreshClasseTable();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "ID Classe doit être un nombre valide !", "Erreur", JOptionPane.ERROR_MESSAGE);
            } catch (Exception e) {
                logger.log(Level.SEVERE, "Erreur lors de l'ajout/mise à jour : " + e.getMessage());
                JOptionPane.showMessageDialog(this, "Une erreur est survenue : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_addClasseButtonActionPerformed

    private void editClasseButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editClasseButtonActionPerformed
        // TODO add your handling code here:
      int selectedRow = classeTable.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) classeTable.getModel();
            String idClasseStr = model.getValueAt(selectedRow, 0).toString();
            String niveau = model.getValueAt(selectedRow, 1).toString();

            idclasseTextField.setText(idClasseStr);
            idclasseTextField.setEditable(false);
            niveauComboBox.setSelectedItem(niveau);
            addClasseButton.setText("Save");
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner une classe à modifier !", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_editClasseButtonActionPerformed

    private void deleteClasseButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteClasseButtonActionPerformed
        // TODO add your handling code here:
       int selectedRow = classeTable.getSelectedRow();
        logger.info("Ligne sélectionnée : " + selectedRow); // Ajout pour débogage
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) classeTable.getModel();
            String idClasseStr = model.getValueAt(selectedRow, 0).toString();
            int idClasse = Integer.parseInt(idClasseStr);

            int confirm = JOptionPane.showConfirmDialog(this, "Êtes-vous sûr de vouloir supprimer la classe avec ID " + idClasse + " ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    ClasseControllers controller = new ClasseControllers();
                    controller.deleteClasse(idClasse);
                    refreshClasseTable();
                    JOptionPane.showMessageDialog(this, "Classe supprimée avec succès !");
                } catch (Exception e) {
                    logger.log(Level.SEVERE, "Erreur lors de la suppression : " + e.getMessage());
                    JOptionPane.showMessageDialog(this, "Une erreur est survenue : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner une classe à supprimer !", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_deleteClasseButtonActionPerformed
private void clearClasseFields() {
        idclasseTextField.setText("");
        niveauComboBox.setSelectedIndex(0);
    }
