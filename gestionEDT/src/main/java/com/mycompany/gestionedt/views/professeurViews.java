public void refreshTable(){
    ProfesseurControllers controller = new ProfesseurControllers();
    ArrayList<ProfesseurModels> professeurs = controller.getAllProfesseurs(); // Récupère la liste
    // Définir le modèle de la table
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Prof");
    model.addColumn("Nom");
    model.addColumn("Prénom");
    model.addColumn("Grade");

for (ProfesseurModels prof : professeurs) {
        model.addRow(new Object[]{
            prof.getIdProf(),
            prof.getNomProf(),
            prof.getPrenomProf(),
            prof.getGrade()
});
}

//appliquer la model du table

ListProfTable.setModel(model);
}

private void filterTable() {
    String searchText = SearchProfTextField.getText().trim().toLowerCase();
    ProfesseurControllers controller = new ProfesseurControllers();
    ArrayList<ProfesseurModels> allProfesseurs = controller.getAllProfesseurs();

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Prof");
    model.addColumn("Nom");
    model.addColumn("Prénom");
    model.addColumn("Grade");

    for (ProfesseurModels prof : allProfesseurs) {
        String nomProf = prof.getNomProf().toLowerCase();
        if (nomProf.contains(searchText)) { // Filtre par nom
            model.addRow(new Object[]{
                prof.getIdProf(),
                prof.getNomProf(),
                prof.getPrenomProf(),
                prof.getGrade()
            });
        }
    }

    ListProfTable.setModel(model);
}

