    private void addprofButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addprofButtonActionPerformed
        // TODO add your handling code here:
        String idProf = idprofField.getText().trim();
        String NomProf = nameprofField.getText();
        String PrenomProf = prenomField.getText();
        String Grade = gradeprofComboBox.getSelectedItem() != null ? gradeprofComboBox.getSelectedItem().toString().trim() : "";

     if(!idProf.isEmpty() && !NomProf.isEmpty() && !PrenomProf.isEmpty() && !Grade.isEmpty()) {
        ProfesseurControllers controller = new ProfesseurControllers();
        
        if (addprofButton.getText().equals("Save")) {//verifie la cas
            // Mode mise à jour
            ProfesseurModels prof = new ProfesseurModels(idProf, NomProf, PrenomProf, Grade);
            controller.updateProfesseur(prof); // Nouvelle méthode pour la mise à jour
            JOptionPane.showMessageDialog(this, "Professeur mis à jour avec succès ! ID : " + idProf);
            addprofButton.setText("Ajouter"); // Revenir à Ajouter
            idprofField.setEditable(true); // Réactiver l'édition de idProf
        }else{
            // Mode ajout
            ProfesseurModels prof = controller.ajouterProfesseur(idProf, NomProf, PrenomProf, Grade);
            JOptionPane.showMessageDialog(this, "Professeur ajouté avec succès ! ID : " + prof.getIdProf());
        }
      
        idprofField.setText("");
        nameprofField.setText("");
        prenomField.setText("");
        gradeprofComboBox.setSelectedIndex(0);
        refreshTable();
    } else {
        JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !", "Erreur", JOptionPane.ERROR_MESSAGE);
    
    }
        
                
    }//GEN-LAST:event_addprofButtonActionPerformed

    private void EditProfButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditProfButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = ListProfTable.getSelectedRow();
    if (selectedRow != -1) { // Vérifie qu'une ligne est sélectionnée
        DefaultTableModel model = (DefaultTableModel) ListProfTable.getModel();
        String idProf = model.getValueAt(selectedRow, 0).toString();
        String NomProf = model.getValueAt(selectedRow, 1).toString();
        String PrenomProf = model.getValueAt(selectedRow, 2).toString();
        String Grade = model.getValueAt(selectedRow, 3).toString();
        
        // Remplir le formulaire
        idprofField.setText(idProf);
        idprofField.setEditable(false); // Désactiver l'édition de idProf
        nameprofField.setText(NomProf);
        prenomField.setText(PrenomProf);
        gradeprofComboBox.setSelectedItem(Grade); // Assure-toi que les valeurs de la combo matchent
        
        addprofButton.setText("Save");
    } else {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner un professeur à modifier !", "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_EditProfButtonActionPerformed

    private void DeleteProfButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteProfButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = ListProfTable.getSelectedRow();
    if (selectedRow != -1) { // Vérifie qu'une ligne est sélectionnée
        DefaultTableModel model = (DefaultTableModel) ListProfTable.getModel();
        String idProf = model.getValueAt(selectedRow, 0).toString();

        int confirm = JOptionPane.showConfirmDialog(this, "Êtes-vous sûr de vouloir supprimer le professeur avec ID " + idProf + " ?", "Confirmation", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            ProfesseurControllers controller = new ProfesseurControllers();
            controller.deleteProfesseur(idProf); // Nouvelle méthode pour la suppression
            refreshTable(); // Rafraîchir la table après suppression
            JOptionPane.showMessageDialog(this, "Professeur supprimé avec succès !");
            }
    } else {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner un professeur à supprimer !", "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_DeleteProfButtonActionPerformed

